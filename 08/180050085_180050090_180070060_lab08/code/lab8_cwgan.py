def get_WLoss_discriminator(fake_images, true_images, labels):
    ## TODO ##
    score_real = D(true_images, labels).mean()
    # score_real.backward(mone)
    score_fake = D(fake_images, labels).mean()
    # score_fake.backward(one)
    grad_penalty = get_gradient_regularisation(fake_images, true_images, labels)
    # grad_penalty.backward()
    return score_fake - score_real + grad_penalty
    ## TODO ##


def get_gradient_regularisation(fake_images, true_images, labels):
    ## TODO ##
    gradients = get_grad(fake_images, true_images, labels)
    grad_penalty = ((gradients.norm(2, dim=1) - 1)**2).mean() * lamda
    return grad_penalty
    ## TODO ##


def get_grad(fake_images, true_images, labels):
    epsilon = torch.FloatTensor(np.random.uniform(
        size=(fake_images.shape[0], 1, 1, 1))).to(device)
    xbar = epsilon*true_images + (1-epsilon)*fake_images
    xbar.requires_grad_()
    lipschitz_grad = grad(
        outputs=D(xbar, labels).sum(),
        inputs=xbar,
        create_graph=True,
        retain_graph=True)[0]
    return lipschitz_grad.view(xbar.shape[0], -1)

